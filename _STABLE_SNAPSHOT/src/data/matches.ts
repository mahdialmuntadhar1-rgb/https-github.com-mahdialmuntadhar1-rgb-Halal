        "Karbala": ["Karbala City", "Hindiyah"],
        "Najaf": ["Najaf Center", "Kufa"],
        "Wasit": ["Kut", "Suwayrah"],
        "Qadisiyah": ["Diwaniyah", "Afak"],
        "Maysan": ["Amarah", "Al-Maimouna"],
        "Dhi Qar": ["Nasiriyah", "Shatrah"],
